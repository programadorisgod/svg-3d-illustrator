export const CRAFT_MODELS = {
  'desk-computer': renderDeskComputerModel,
  'sorting-desk': renderSortingDeskModel,
  'dial-indicator': renderDialIndicatorModel,
  'server-blade': renderServerBladeModel,
  'bloom-flower': renderBloomFlowerModel,
  'engine-piston': renderEnginePistonModel,
  'astral-bot-card': renderAstralBotCardModel,
  'rocket-launch-card': renderRocketLaunchCardModel,
  'retro-console-card': renderRetroConsoleCardModel
};

export const TEMPLATES = {
  'hero-isometric-grid': renderHeroIsometricGridTemplate,
  'doc-architecture-card': renderDocArchitectureCardTemplate,
  'tech-stack-spotlight': renderTechStackSpotlightTemplate,
  'abstract-aurora-bg': renderAbstractAuroraBgTemplate
};

export const PRIMITIVES = {
  'isometric-box': renderIsometricBoxPrimitive,
  'database-cylinder': renderDatabaseCylinderPrimitive,
  'server-rack': renderServerRackPrimitive,
  'code-terminal': renderCodeTerminalPrimitive,
  'network-node': renderNetworkNodePrimitive,
  'connector-wire': renderConnectorWirePrimitive
};

/**
 * Compila una escena declarativa a código SVG puro y determinista
 */
export function compileScene(sceneSpec = {}) {
  // Modo Craft (Ilustración vectorial 2D/3D de objetos físicos u orgánicos con soporte de color, B&N y animaciones)
  if (sceneSpec.craft || sceneSpec.model) {
    const modelName = sceneSpec.craft || sceneSpec.model;
    const modelFn = CRAFT_MODELS[modelName];
    if (modelFn) {
      return modelFn({
        width: sceneSpec.width,
        height: sceneSpec.height,
        theme: sceneSpec.theme || 'light',
        mode: sceneSpec.mode || (['astral-bot-card', 'rocket-launch-card', 'retro-console-card'].includes(modelName) ? '2d' : '3d'),
        colorMode: sceneSpec.colorMode || (['bloom-flower', 'engine-piston', 'astral-bot-card', 'rocket-launch-card', 'retro-console-card'].includes(modelName) ? 'color' : 'mono'),
        palette: sceneSpec.palette || (modelName === 'bloom-flower' ? 'botanical' : 'vibrant'),
        animate: sceneSpec.animate || (modelName === 'bloom-flower' ? 'bloom' : 'static'),
        showPlate: sceneSpec.showPlate !== undefined ? sceneSpec.showPlate : (['astral-bot-card', 'rocket-launch-card', 'retro-console-card'].includes(modelName) ? false : true),
        ...(sceneSpec.params || {})
      });
    }
  }

  const {
    width = 1000,
    height = 600,
    preset = 'dark-linear',
    customColors = {},
    title = 'Vector Illustration',
    description = 'Deterministic 3D SVG Generated by svg-3d-illustrator',
    template = null,
    mode = 'template',
    projection3d = null,
    elements = [],
    params = {}
  } = sceneSpec;

  const theme = resolveTheme(preset, customColors);
  const defs = createSvgDefs(theme);
  let innerContent = '';

  // Modo 1: Proyección 3D de sólidos
  if (mode === '3d-projection' || projection3d) {
    const config = projection3d || {};
    const primitiveType = config.primitive || 'box';
    let mesh;

    if (primitiveType === 'cylinder') {
      mesh = createCylinderMesh(config.radius || 60, config.height || 100, config.segments || 24);
    } else {
      mesh = createBoxMesh(config.width || 120, config.depth || 120, config.height || 100);
    }

    const meshSvg = render3DMeshToSvg({
      mesh,
      rotation: config.rotation || { x: -25, y: 35, z: 0 },
      origin: config.origin || { x: width / 2, y: height / 2 },
      scale: config.scale || 1.8,
      camera: config.camera || 'perspective',
      fov: config.fov || 500,
      baseColor: config.color || theme.colors.primary,
      stroke: theme.colors.borderBright,
      strokeWidth: 1.2
    });

    innerContent = `
      <rect width="${width}" height="${height}" fill="${theme.colors.background}" />
      <rect width="${width}" height="${height}" fill="url(#dot-pattern)" opacity="0.3" />
      <circle cx="${width / 2}" cy="${height / 2}" r="160" fill="${theme.colors.primary}" opacity="0.1" filter="url(#glow-ambient)" />
      ${meshSvg}
    `;
  }
  // Modo 2: Plantilla prediseñada
  else if (template && TEMPLATES[template]) {
    const templateFn = TEMPLATES[template];
    innerContent = templateFn({
      theme,
      width,
      height,
      ...params
    });
  }
  // Modo 3: Composición de elementos libres
  else if (elements && elements.length > 0) {
    const elementsSvg = elements.map((el, i) => {
      const primFn = PRIMITIVES[el.type];
      if (primFn) {
        return primFn({
          theme,
          id: `elem-${i}`,
          ...el
        });
      }
      return '';
    }).join('\n');

    innerContent = `
      <rect width="${width}" height="${height}" fill="${theme.colors.background}" />
      <rect width="${width}" height="${height}" fill="url(#dot-pattern)" opacity="0.4" />
      ${elementsSvg}
    `;
  } else {
    innerContent = TEMPLATES['hero-isometric-grid']({
      theme,
      width,
      height,
      ...params
    });
  }

  return wrapSvgDocument({
    content: innerContent,
    defs,
    width,
    height,
    title,
    description
  });
}
